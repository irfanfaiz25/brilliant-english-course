import "server-only";

import { mkdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";

import {
  DeleteObjectCommand,
  GetObjectCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

import { limits } from "@/config/limits";
import { env } from "@/lib/env";

import { signUploadToken } from "./upload-token";

/** Where the browser sends the file: a PUT with these headers and the file as the body. */
export type UploadTarget = { url: string; headers: Record<string, string> };

export type StorageDriver = {
  name: "r2" | "local";
  /** A short-lived URL the browser may PUT exactly this object to. */
  uploadTarget(key: string, contentType: string): Promise<UploadTarget>;
  /** The object's bytes; `null` when it is missing or larger than `maxBytes`. */
  read(key: string, maxBytes: number): Promise<Buffer | null>;
  write(key: string, body: Buffer, contentType: string): Promise<void>;
  /** Removes the object; a missing object is not an error. */
  remove(key: string): Promise<void>;
};

/** Object keys are generated by the app (`tmp/<uuid>`, `media/2026/11/<uuid>.webp`). */
export function isSafeKey(key: string): boolean {
  return /^[a-z0-9][a-z0-9/._-]*$/.test(key) && !key.includes("..") && !key.includes("//");
}

/** Stored images never change under their key, so they may be cached for a year. */
export const immutableCache = "public, max-age=31536000, immutable";

const uploadSeconds = limits.media.uploadUrlMinutes * 60;

function r2Driver(config: {
  accountId: string;
  accessKeyId: string;
  secretAccessKey: string;
  bucket: string;
}): StorageDriver {
  const client = new S3Client({
    region: "auto",
    endpoint: `https://${config.accountId}.r2.cloudflarestorage.com`,
    credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
    // R2 rejects the checksum headers newer SDKs add by default to presigned browser uploads.
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
  });
  const Bucket = config.bucket;

  return {
    name: "r2",
    async uploadTarget(key, contentType) {
      const url = await getSignedUrl(
        client,
        new PutObjectCommand({ Bucket, Key: key, ContentType: contentType }),
        { expiresIn: uploadSeconds, signableHeaders: new Set(["content-type"]) },
      );
      return { url, headers: { "Content-Type": contentType } };
    },
    async read(key, maxBytes) {
      try {
        const object = await client.send(new GetObjectCommand({ Bucket, Key: key }));
        if (!object.Body || (object.ContentLength ?? 0) > maxBytes) return null;
        return Buffer.from(await object.Body.transformToByteArray());
      } catch (error) {
        if (error instanceof Error && error.name === "NoSuchKey") return null;
        throw error;
      }
    },
    async write(key, body, contentType) {
      await client.send(
        new PutObjectCommand({
          Bucket,
          Key: key,
          Body: body,
          ContentType: contentType,
          CacheControl: immutableCache,
        }),
      );
    },
    async remove(key) {
      await client.send(new DeleteObjectCommand({ Bucket, Key: key }));
    },
  };
}

/** Folder of the local driver (git-ignored). Served by `/api/media/files/[...key]`. */
export const localStorageDir = path.join(process.cwd(), ".storage");

/** Path of a key inside the local folder; throws for keys that could leave it. */
export function localPath(key: string): string {
  if (!isSafeKey(key)) throw new Error(`Unsafe storage key: ${key}`);
  return path.join(localStorageDir, ...key.split("/"));
}

function localDriver(): StorageDriver {
  return {
    name: "local",
    async uploadTarget(key, contentType) {
      const token = signUploadToken(
        { key, contentType, expiresAt: Date.now() + uploadSeconds * 1000 },
        env.BETTER_AUTH_SECRET,
      );
      return {
        url: `/api/media/upload?token=${encodeURIComponent(token)}`,
        headers: { "Content-Type": contentType },
      };
    },
    async read(key, maxBytes) {
      const file = localPath(key);
      const info = await stat(file).catch(() => null);
      if (!info?.isFile() || info.size > maxBytes) return null;
      return readFile(file);
    },
    async write(key, body) {
      const file = localPath(key);
      await mkdir(path.dirname(file), { recursive: true });
      await writeFile(file, body);
    },
    async remove(key) {
      await rm(localPath(key), { force: true });
    },
  };
}

/**
 * The media storage: Cloudflare R2 when the `R2_*` variables are set, otherwise the local
 * `.storage/` folder (development and CI). Both take uploads straight from the browser (ADR-031).
 */
export const storage: StorageDriver =
  env.R2_ACCOUNT_ID && env.R2_ACCESS_KEY_ID && env.R2_SECRET_ACCESS_KEY && env.R2_BUCKET
    ? r2Driver({
        accountId: env.R2_ACCOUNT_ID,
        accessKeyId: env.R2_ACCESS_KEY_ID,
        secretAccessKey: env.R2_SECRET_ACCESS_KEY,
        bucket: env.R2_BUCKET,
      })
    : localDriver();
